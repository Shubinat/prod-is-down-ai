def generate_sentences() -> list[str]:
    sentences = [
        line.strip()
        for line in STORIES.splitlines()
        if line.strip()
    ]

    for role in ROLES:
        for module in MODULES:
            sentences.extend([
                f"{role} нашёл баг в {module} и завёл тикет.",
                f"{role} исправил ошибку в {module}, но забыл про тесты.",
                f"{role} проверил логи в {module} и вызвал тимлида.",
                f"{role} обсуждал проблему в {module} до самого вечера.",
                f"{role} улучшил код в {module}, а прод всё равно упал.",
            ])

    for role in ROLES:
        for tool in TOOLS:
            sentences.extend([
                f"{role} запустил {tool} и ушёл за кофе.",
                f"{role} проверил {tool} перед релизом.",
                f"{role} случайно сломал {tool} во время созвона.",
                f"{role} починил {tool} и написал документацию.",
            ])

    for role in ROLES:
        for incident in INCIDENTS:
            sentences.extend([
                f"на стендапе {role} сказал, что {incident}.",
                f"{role} заметил, что {incident}, и открыл тикет.",
                f"{role} объяснил команде, почему {incident}.",
            ])

    sentences = list(dict.fromkeys(sentences))

    rng.shuffle(sentences)

    return sentences


def main():
    sentences = generate_sentences()

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(
        "\n".join(sentences) + "\n",
        encoding="utf-8",
    )

    text = OUTPUT.read_text(encoding="utf-8")
    tokens = re.findall(r"[а-яёa-z0-9]+|[.!?,:]", text.lower())

    print("Предложений:", len(sentences))
    print("Токенов:", len(tokens))
    print("Уникальных токенов:", len(set(tokens)))
    print("Размер файла:", OUTPUT.stat().st_size, "байт")
    print("\nПримеры:")

    for line in sentences[:5]:
        print("-", line)


if __name__ == "__main__":
    main()
